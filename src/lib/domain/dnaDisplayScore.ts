import { clamp } from "./normalize";

/**
 * 내부 분석점수(0~100, DNA 산식·최소-최대 정규화 결과)와 사용자 표시용 지수를 분리하는 계층
 * (2026-08-07). DNA 산식(dna.ts)·정규화 공식(normalize.ts)·전략 계산은 이 파일을 전혀 참조하지
 * 않는다 — 오직 화면에 숫자를 그리기 직전에만 사용한다.
 *
 * 배경: 27개 지역 실제 분포를 조사한 결과, 수요·체류·소비·다양성 축은 지역별로 0점·100점이 실제로
 * 나타나 사용자가 "관광 수요가 전혀 없다"/"완벽한 다양성"처럼 절대평가로 오해할 위험이 컸다. 설명
 * 문구만으로는 숫자 자체가 주는 인상을 상쇄하기 어려워, 표시 계층에서 극단부를 완화한다.
 *
 * 채택한 방식(단순 선형 압축, "A안"): 내부 0~100을 표시 10~90으로 균등 비율로 압축한다. 모든
 * 지역·모든 축에 동일한 규칙을 적용하므로 상대적 순위·비율 관계가 정확히 보존된다("40과 60의 차이"
 * 같은 관계가 왜곡되지 않는다는 뜻). 27개 지역 실제 데이터로 시그모이드 계열(중앙권을 오히려 확대해
 * 왜곡)과 구간별 압축(구간 경계에서 인위적인 굴절, 상위 구간 변별력 손실)을 함께 비교한 결과, 이
 * 방식이 "중간권 왜곡 최소화·설명 용이성·구현 단순성" 기준에서 가장 우수했다.
 */

/** 표시 지수의 최소·최댓값. 이 범위 밖의 표시 지수는 나오지 않는다 — 0도 100도 화면에 그대로
 * 노출되지 않는다는 뜻이다. */
export const DISPLAY_SCORE_MIN = 10;
export const DISPLAY_SCORE_MAX = 90;

/**
 * 내부 분석점수를 사용자 표시용 지수로 변환한다. 동일 입력은 항상 동일 출력이며(결정론적),
 * 단조 증가 함수라 순위가 뒤바뀌지 않는다. 이 함수는 화면 표시에만 쓰고 강점/개선 판정이나 전략
 * 계산에는 절대 쓰지 않는다 — 그 판정은 반드시 원본 내부 분석점수로 한다.
 */
export function toDisplayDnaScore(internalScore: number | null): number | null {
  if (internalScore === null) return null;
  const ratio = clamp(internalScore, 0, 100) / 100;
  return Math.round(DISPLAY_SCORE_MIN + (DISPLAY_SCORE_MAX - DISPLAY_SCORE_MIN) * ratio);
}
